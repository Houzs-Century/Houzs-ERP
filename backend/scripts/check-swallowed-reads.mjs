#!/usr/bin/env node
// ---------------------------------------------------------------------------
// check-swallowed-reads.mjs — a read whose failure is discarded may not become
// more common. Exit 1 when any file exceeds its committed ceiling.
//
// See scripts/lib/swallowed-read-scan.mjs for the shape, what it cost, and why
// this is a ratchet rather than a ban.
//
// WHY A SCRIPT AND NOT A TEST. It has to see BOTH trees. The backend suite runs
// in workerd and has no filesystem; the frontend suite cannot read backend/src.
// The existing partial guard, frontend/src/auth/permissionDivergence.test.ts,
// is the argument for scanning rather than enumerating: it asserts that no bare
// `.catch(() => {})` remains — in a hand-written SITES array naming exactly the
// TWO files that had already broken. 37 more exist in frontend/src today and
// every one of them passes that test.
//
// READ-ONLY. Touches no database and no network — it reads files.
//
//   node backend/scripts/check-swallowed-reads.mjs             # exit 1 if grown
//   node backend/scripts/check-swallowed-reads.mjs --update    # rewrite ceilings
//   npm --prefix backend run audit:swallowed-reads
// ---------------------------------------------------------------------------

import { readFileSync, readdirSync, statSync, writeFileSync } from 'node:fs';
import { dirname, join, relative, resolve, sep } from 'node:path';
import { fileURLToPath } from 'node:url';
import { scanErrorlessReads, scanBareCatches } from './lib/swallowed-read-scan.mjs';

const HERE = dirname(fileURLToPath(import.meta.url));
const BACKEND = resolve(HERE, '..');
const REPO = resolve(BACKEND, '..');
const BASELINE = join(BACKEND, 'scripts/data/swallowed-read-baseline.json');

const ROOTS = [
  { dir: join(BACKEND, 'src'), ext: /\.ts$/ },
  { dir: join(REPO, 'frontend/src'), ext: /\.tsx?$/ },
];
const SKIP_DIR = new Set(['node_modules', 'dist', '.wrangler', 'artifacts']);
const isTest = (p) => /\.(test|spec)\.tsx?$/.test(p) || /(^|\/)(tests|__tests__)\//.test(p);

function* walk(dir, ext) {
  for (const name of readdirSync(dir)) {
    if (SKIP_DIR.has(name)) continue;
    const full = join(dir, name);
    if (statSync(full).isDirectory()) yield* walk(full, ext);
    else if (ext.test(name)) yield full;
  }
}

// -- census -----------------------------------------------------------------
/** @type {Record<string, {reads:number, catches:number}>} */
const actual = {};
for (const { dir, ext } of ROOTS) {
  for (const file of walk(dir, ext)) {
    // Forward slashes, always. The baseline JSON is written by CI on Linux, so
    // its 126 keys are posix; relative() hands back backslashes on Windows and
    // every ceiling lookup missed, reporting the whole tree as 153 NEW sites.
    const rel = relative(REPO, file).split(sep).join('/');
    if (isTest(rel)) continue;
    const text = readFileSync(file, 'utf8');
    const reads = scanErrorlessReads(text).length;
    const catches = scanBareCatches(text).length;
    if (reads || catches) actual[rel] = { reads, catches };
  }
}

const sum = (k) => Object.values(actual).reduce((a, v) => a + v[k], 0);

if (process.argv.includes('--update')) {
  const sorted = Object.fromEntries(Object.entries(actual).sort(([a], [b]) => a.localeCompare(b)));
  writeFileSync(
    BASELINE,
    `${JSON.stringify(
      {
        _README: [
          'Per-file CEILINGS for reads whose failure is discarded. Generated by',
          'backend/scripts/check-swallowed-reads.mjs --update. These numbers may only',
          'go DOWN. A PR that adds a site fails; a PR that removes one must lower the',
          'ceiling here in the same commit, which is what makes the ratchet descend.',
          'reads   = `const { data ... } = await ...` with no `error` bound.',
          'catches = `.catch(() => {})` and its silent siblings.',
          'A file absent from this map has a ceiling of zero.',
        ],
        files: sorted,
      },
      null,
      2,
    )}\n`,
  );
  console.log(`Wrote ${relative(REPO, BASELINE)} — ${Object.keys(sorted).length} files, ${sum('reads')} reads, ${sum('catches')} catches.`);
  process.exit(0);
}

let baseline;
try {
  baseline = JSON.parse(readFileSync(BASELINE, 'utf8')).files;
} catch {
  console.error(`Missing or unreadable ${relative(REPO, BASELINE)}.`);
  console.error('Create it with: node backend/scripts/check-swallowed-reads.mjs --update');
  process.exit(1);
}

// -- compare ----------------------------------------------------------------
const grown = [];
const improved = [];
for (const [file, counts] of Object.entries(actual)) {
  const ceil = baseline[file] ?? { reads: 0, catches: 0 };
  for (const kind of ['reads', 'catches']) {
    if (counts[kind] > ceil[kind]) grown.push({ file, kind, was: ceil[kind], now: counts[kind] });
    else if (counts[kind] < ceil[kind]) improved.push({ file, kind, was: ceil[kind], now: counts[kind] });
  }
}
for (const [file, ceil] of Object.entries(baseline)) {
  if (actual[file]) continue;
  for (const kind of ['reads', 'catches']) {
    if (ceil[kind] > 0) improved.push({ file, kind, was: ceil[kind], now: 0 });
  }
}

console.log('reads whose failure is discarded');
console.log(`  const { data } with no error : ${sum('reads')}`);
console.log(`  bare .catch(() => {})        : ${sum('catches')}`);
console.log(`  files carrying at least one  : ${Object.keys(actual).length}`);

if (grown.length === 0 && improved.length === 0) {
  console.log('\nAt the ceiling, exactly. No file gained a swallowed read.');
  process.exit(0);
}

if (grown.length > 0) {
  console.error(`\nA READ'S FAILURE IS BEING DISCARDED IN ${grown.length} NEW PLACE(S).\n`);
  console.error('supabase-js does not throw. `const { data } = await sb...` with no');
  console.error('`error` bound cannot tell "the query failed" or "you are not allowed"');
  console.error('from "there is nothing here" — and the next line writes it. This is');
  console.error('how a five-second database blip became money collected twice at the');
  console.error('door (BUG-HISTORY 2026-07-17) and a credit spent twice.\n');
  for (const g of grown) console.error(`  ${g.file}  ${g.kind} ${g.was} -> ${g.now}`);
  console.error('\nBind the error and branch on it:');
  console.error('    const { data, error } = await sb.from(...).select(...);');
  console.error('    if (error) return c.json({ error: "..." }, 500);   // NOT `data ?? []`');
  console.error('    const rows = data ?? [];   // now this really does mean "empty"');
  console.error('\nRaising the ceiling in swallowed-read-baseline.json is not the fix.');
  console.error('The ceiling exists because 938 sites predate the rule, not to make room.\n');
}

if (improved.length > 0) {
  console.error(`\n${improved.length} ceiling(s) are now ABOVE the real count — lower them.\n`);
  console.error('A ratchet that is never tightened is a ceiling nobody is under. Run:');
  console.error('    node backend/scripts/check-swallowed-reads.mjs --update');
  console.error('and commit the smaller numbers with the fix that earned them.\n');
  for (const g of improved.slice(0, 20)) console.error(`  ${g.file}  ${g.kind} ${g.was} -> ${g.now}`);
  if (improved.length > 20) console.error(`  ... and ${improved.length - 20} more`);
}
process.exit(1);
