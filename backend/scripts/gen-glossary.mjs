#!/usr/bin/env node
/* ---------------------------------------------------------------------------
   gen-glossary.mjs — the page a HUMAN reads to find out what a thing is called.

   Owner 2026-08-18: 「我跟你讲 Processing Date, 你却去找成 Process Date ...
   这种问题其实也是名词的统一」. The answer already existed in the tree —
   `so-processing-date.mjs` says in plain text which spelling is current and
   which is retired — but only PROGRAMS read that file, so a person asking "what
   is this called" had nowhere to look.

   GENERATED, NEVER HAND-WRITTEN, and that is the whole point. A hand-written
   glossary is one more document to keep in sync, which is the problem this is
   supposed to solve rather than enlarge. This one is derived from
   `scripts/lib/vocabulary.mjs`, so it cannot say something the guard does not
   also enforce, and `--check` fails when the committed page has drifted from
   the registry.

   RE-RUN: `npm --prefix backend run gen:glossary` writes the page.
           `npm --prefix backend run audit:glossary` fails if it is stale.
   --------------------------------------------------------------------------- */
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

import { VOCABULARY, ALWAYS_HISTORICAL } from "./lib/vocabulary.mjs";
import { DRIFT_CATALOGUE } from "./lib/drift-catalogue.mjs";

const here = path.dirname(fileURLToPath(import.meta.url));
const OUT = path.join(here, "..", "..", "docs", "generated", "GLOSSARY.md");
const CHECK = process.argv.includes("--check");

const render = () => {
  const L = [];
  L.push("# Glossary — one word per concept");
  L.push("");
  L.push("<!-- GENERATED by backend/scripts/gen-glossary.mjs — do not edit by hand.");
  L.push("     Add a concept in backend/scripts/lib/vocabulary.mjs and re-run");
  L.push("     `npm --prefix backend run gen:glossary`. -->");
  L.push("");
  L.push("This page exists because the same thing had several spellings, and every");
  L.push("conversation started by re-agreeing which one we meant. Say the word in the");
  L.push("**Say this** column; if you meet a word from **Not this**, it is a leftover.");
  L.push("");
  L.push("A retired spelling is allowed in a COMMENT — a rename is a story worth telling —");
  L.push("and in the migrations that performed it. `npm --prefix backend run audit:vocabulary`");
  L.push("fails when one appears in CODE.");
  L.push("");
  L.push("| Concept | Say this | Not this | Declared in |");
  L.push("| --- | --- | --- | --- |");
  for (const e of VOCABULARY) {
    const say = [e.canonical, ...(e.alsoCanonical ?? [])].map((c) => `\`${c}\``).join(" / ");
    const not = e.retired.length ? e.retired.map((r) => `~~\`${r}\`~~`).join("<br>") : "—";
    L.push(`| **${e.concept}** | ${say} | ${not} | \`${e.declaredIn}\` |`);
  }
  L.push("");
  L.push("## What each one means");
  L.push("");
  for (const e of VOCABULARY) {
    L.push(`### ${e.concept}`);
    L.push("");
    L.push(e.note);
    L.push("");
    if (e.allow.length) {
      L.push(`Entitled to spell a retired name in code: ${e.allow.map((a) => `\`${a}\``).join(", ")}.`);
      L.push("");
    }
  }
  L.push("## Concepts still carrying several spellings — the unification worklist");
  L.push("");
  L.push("Found by the 2026-08-18 full-codebase screening. These are DOCUMENTED, not yet");
  L.push("enforced: each is retired one concept at a time (a migration per concept, batch 2).");
  L.push("Until then, prefer the **Target** spelling in new code.");
  L.push("");
  L.push("| Sev | Concept | Target | Also seen as |");
  L.push("| --- | --- | --- | --- |");
  const sevOrder = { high: 0, med: 1, low: 2 };
  for (const c of [...DRIFT_CATALOGUE].sort((a, b) => (sevOrder[a.severity] ?? 3) - (sevOrder[b.severity] ?? 3))) {
    const also = c.seen.filter((x) => x.split(" ")[0] !== c.canonical).map((x) => "`" + x.split(" ")[0] + "`").slice(0, 5).join(" ");
    L.push(`| ${c.severity} | ${c.concept} | \`${c.canonical}\` | ${also} |`);
  }
  L.push("");
  L.push("## Where a retired spelling is not a defect");
  L.push("");
  for (const h of ALWAYS_HISTORICAL) L.push(`- \`${h}\` — records the rename it performed`);
  L.push("- any comment — the history is worth keeping next to the code it explains");
  L.push("");
  return L.join("\n");
};

const body = render();
if (CHECK) {
  const current = fs.existsSync(OUT) ? fs.readFileSync(OUT, "utf8") : "";
  if (current.replace(/\r\n/g, "\n") !== body) {
    console.error(
      "docs/generated/GLOSSARY.md is stale.\n" +
        "The registry in backend/scripts/lib/vocabulary.mjs changed and the page was not regenerated.\n" +
        "Run: npm --prefix backend run gen:glossary",
    );
    process.exit(1);
  }
  console.log(`GLOSSARY.md is current — ${VOCABULARY.length} enforced + ${DRIFT_CATALOGUE.length} documented concept(s).`);
} else {
  fs.mkdirSync(path.dirname(OUT), { recursive: true });
  fs.writeFileSync(OUT, body);
  console.log(`wrote docs/generated/GLOSSARY.md — ${VOCABULARY.length} enforced + ${DRIFT_CATALOGUE.length} documented concept(s)`);
}
