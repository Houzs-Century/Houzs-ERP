#!/usr/bin/env node
// ---------------------------------------------------------------------------
// fix-so-line-totalheight.mjs — add the missing totalHeight to ONE SO line's
// variants, so its key agrees with its own DO and doc-relabel can converge.
//
// THE CASE (2026-08-05, doc-relabel run 31002422064). TRION-(K) on
// 2990-SO-2606-038: the SO line's variants carry gap/divan/leg but NO
// totalHeight, while the DO line (2990-DO-2607-009) carries totalHeight "24"".
// `computeVariantKey` includes totalheight for bedframes (ATTRS_BY_GROUP), so
// the two documents compute different keys for the same physical bedframe and
// doc-relabel refuses with `doc-conflict` — correctly, because it must not
// guess which document is right.
//
// Here the answer is not a guess: the DO carries the value, the SO's own
// summary implies it (Divan 8" + Gap 15" + Leg 1" -> 24"), and the owner
// approved the fix. This adds `totalHeight` to that ONE line's variants and
// nothing else. `description2` is regenerated by the app on the next line
// save; the stored one is display-only and is left alone.
//
// DRY-RUN BY DEFAULT; APPLY=true + CONFIRM phrase to write. Scoped hard: doc
// number, item code and the value all come from env and default to this case.
//
//   SO="2990-SO-2606-038" ITEM="TRION-(K)" VALUE='24"' \
//   APPLY=true CONFIRM="I HAVE REVIEWED THE DRY-RUN" node backend/scripts/fix-so-line-totalheight.mjs
// ---------------------------------------------------------------------------

import { readFileSync } from "node:fs";
import postgres from "postgres";

function resolveUrl() {
  if (process.env.DATABASE_URL) return process.env.DATABASE_URL;
  try {
    return readFileSync(".dev.vars", "utf8").match(/DATABASE_URL="([^"]+)"/)?.[1];
  } catch {
    return undefined;
  }
}

const url = resolveUrl();
if (!url) {
  console.error("DATABASE_URL not set (env var or .dev.vars). Aborting.");
  process.exit(1);
}

const SO = (process.env.SO || "2990-SO-2606-038").trim();
const ITEM = (process.env.ITEM || "TRION-(K)").trim();
const VALUE = (process.env.VALUE || '24"').trim();

const CONFIRM_PHRASE = "I HAVE REVIEWED THE DRY-RUN";
const APPLY = process.env.APPLY === "true" && process.env.CONFIRM === CONFIRM_PHRASE;
if (process.env.APPLY === "true" && !APPLY) {
  console.log(`APPLY requested but CONFIRM did not match "${CONFIRM_PHRASE}" — running DRY-RUN instead.\n`);
}

const pg = postgres(url, { ssl: "require", prepare: false, max: 1 });

try {
  console.log(`\nSO LINE totalHeight FIX — ${APPLY ? "APPLY (will be COMMITTED)" : "DRY-RUN (nothing will be written)"}`);
  console.log(`target: ${SO} · ${ITEM} · totalHeight="${VALUE}"\n`);

  const rows = await pg`
    SELECT i.id, i.item_code, i.item_group, i.variants
      FROM scm.mfg_sales_order_items i
      JOIN scm.mfg_sales_orders o ON o.id = i.sales_order_id
     WHERE o.doc_no = ${SO} AND i.item_code = ${ITEM}`;

  if (rows.length === 0) {
    console.log("No such line. Nothing to do.");
    process.exit(0);
  }
  if (rows.length > 1) {
    console.log(`${rows.length} lines match — refusing to guess which one. Narrow the target.`);
    process.exit(1);
  }

  const line = rows[0];
  const v = line.variants ?? {};
  console.log(`line ${line.id} (${line.item_group ?? "?"})`);
  console.log(`variants BEFORE: ${JSON.stringify(v)}`);

  if (v.totalHeight != null && String(v.totalHeight).trim() !== "") {
    console.log(`\ntotalHeight already present ("${v.totalHeight}") — nothing to do.`);
    process.exit(0);
  }

  const after = { ...v, totalHeight: VALUE };
  console.log(`variants AFTER : ${JSON.stringify(after)}`);

  if (APPLY) {
    await pg`UPDATE scm.mfg_sales_order_items SET variants = ${after} WHERE id = ${line.id}`;
    console.log(`\nAPPLIED. Now run doc-relabel DRY-RUN — the doc-conflict on this line should be gone.`);
  } else {
    console.log(`\nDRY-RUN — nothing written. Re-run with APPLY=true CONFIRM="${CONFIRM_PHRASE}".`);
  }
} finally {
  await pg.end({ timeout: 5 });
}
