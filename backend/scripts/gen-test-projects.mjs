// Splits the backend suite into the two runners it actually needs.
//
// Why. Every file under the workers pool boots its own workerd instance with
// its own isolated D1, and vitest.config.mts runs them one at a time
// (`fileParallelism: false` — the pool collapses above that). Measured
// 2026-08-13: ~1.76s of startup per file, 278 files, and the full suite was
// `565s, of which setup is 490s and the tests themselves are 10.9s`.
//
// Of 265 files in that pool, **44** touch `cloudflare:test` or a D1 binding.
// The other 221 are pure logic paying a runtime they never use. Run on a plain
// node runner they complete in **6.09s** — all 221 files, 3433 tests, green —
// against ~390s of workerd startup for the same set.
//
// So the split is by need, not by taste: a file that reaches for the Workers
// runtime gets the Workers runtime, and nothing else does. This is generated
// rather than hand-listed because a hand-listed one rots silently — a new test
// lands in whichever project someone guessed, and the only symptom is the
// suite slowly getting slower again. `--check` runs in CI.

import fs from "node:fs/promises";
import path from "node:path";
import { fileURLToPath } from "node:url";

const here = path.dirname(fileURLToPath(import.meta.url));
const backendRoot = path.join(here, "..");
const OUT = path.join(backendRoot, "tests/generated/test-projects.json");

// The two Workers-runtime tells. `cloudflare:test` is the module that only
// exists inside the pool; `env.DB` / `env.DB_PARITY` are the D1 bindings it
// hands out. A file mentioning either cannot run anywhere else.
const NEEDS_WORKERS = /\bcloudflare:test\b|\benv\.DB\b|\benv\.DB_PARITY\b/;

// Suites with their own config and their own runner already.
const OWNED_ELSEWHERE = ["tests-pg/", "tests-node/"];

async function* walk(dir) {
  for (const entry of await fs.readdir(dir, { withFileTypes: true })) {
    if (entry.name === "node_modules" || entry.name.startsWith(".")) continue;
    const full = path.join(dir, entry.name);
    if (entry.isDirectory()) yield* walk(full);
    else if (/\.test\.ts$/.test(entry.name)) yield full;
  }
}

const workers = [];
const light = [];
for (const root of ["tests", "src"]) {
  const abs = path.join(backendRoot, root);
  if (!(await fs.stat(abs).catch(() => null))) continue;
  for await (const file of walk(abs)) {
    const rel = path.relative(backendRoot, file).split(path.sep).join("/");
    if (OWNED_ELSEWHERE.some((p) => rel.startsWith(p))) continue;
    const source = await fs.readFile(file, "utf8");
    (NEEDS_WORKERS.test(source) ? workers : light).push(rel);
  }
}
workers.sort();
light.sort();

const payload =
  JSON.stringify(
    {
      _comment:
        "GENERATED by scripts/gen-test-projects.mjs — DO NOT EDIT. " +
        "Run `npm run gen:test-projects` after adding or moving a test file.",
      workers,
      light,
    },
    null,
    2,
  ) + "\n";

if (process.argv.includes("--check")) {
  const have = await fs.readFile(OUT, "utf8").catch(() => null);
  if (have !== payload) {
    const prev = have ? JSON.parse(have) : { workers: [], light: [] };
    const added = [...workers, ...light].filter(
      (f) => ![...prev.workers, ...prev.light].includes(f),
    );
    const moved = workers.filter((f) => prev.light?.includes(f));
    console.error(
      "Test project split is stale.\n" +
        (added.length ? `  new test files: ${added.join(", ")}\n` : "") +
        (moved.length
          ? `  now need the Workers runtime: ${moved.join(", ")}\n`
          : "") +
        "A file in the wrong project either cannot run at all, or silently\n" +
        "pays ~1.76s of workerd startup it does not need.\n" +
        "Fix: npm run gen:test-projects",
    );
    process.exit(1);
  }
  console.log(
    `test project split up to date (${workers.length} workers, ${light.length} light)`,
  );
} else {
  await fs.mkdir(path.dirname(OUT), { recursive: true });
  await fs.writeFile(OUT, payload);
  console.log(
    `wrote ${path.relative(backendRoot, OUT)}\n` +
      `  ${workers.length} need the Workers runtime, ${light.length} do not`,
  );
}
