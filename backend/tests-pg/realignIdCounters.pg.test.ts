// @ts-expect-error — plain .mjs helper, no types; the SAME splitter pg-migrate.mjs uses.
import { splitSqlStatements } from '../scripts/lib/split-sql.mjs';

/* Team > Members > Save failed with "Something went wrong processing that
 * request." (James Lee Jun Ji, 2026-10-21): rows written into sales_reps with
 * explicit ids left its id counter behind the table, so the roster INSERT that
 * PATCH /api/users/:id runs for a Sales member raised duplicate key. The
 * migration moves such counters forward and adds the roster row the failed
 * save never wrote. SKIPPED without TEST_DATABASE_URL (CI: backend-postgres ->
 * npm run test:pg). */

const url = process.env.TEST_DATABASE_URL ?? '';
const describePg = url ? describe : describe.skip;
const DB = 'realign_id_counters';
const migrationsDir = fileURLToPath(new URL('../src/db/migrations-pg/', import.meta.url));

async function applyMigration(sql: Sql): Promise<void> {
  const files = (await readdir(migrationsDir)).filter((f) => f.endsWith('_realign_id_counters.sql'));
  if (files.length !== 1) throw new Error(`expected one *_realign_id_counters.sql, found ${files.length}`);
  const stmts = splitSqlStatements(await readFile(join(migrationsDir, files[0]!), 'utf8')) as string[];
  await sql.begin(async (tx) => { for (const s of stmts) await tx.unsafe(s); });
}

// Production's shapes: identity BY DEFAULT on the roster tables, a plain serial
// keyed by an id the app always supplies, and a counter already ahead.
