// What syncSalesRepFromUser sends through the d1 shim, which appends RETURNING *.
const APP_ROSTER_INSERT = `INSERT INTO sales_reps (code, name, email, user_id, status) VALUES ($1, $2, $3, $4, 'active') RETURNING *`;

let admin: Sql;
let a: Sql;

function urlFor(db: string): string {
  const u = new URL(url);
  u.pathname = `/${db}`;
  return u.toString();
}

async function codeOf(p: Promise<unknown>): Promise<string | null> {
  try { await p; return null; } catch (e) { return (e as { code?: string }).code ?? 'unknown'; }
}

async function counter(seq: string): Promise<{ last: number; called: boolean }> {
  const [r] = await a.unsafe(`SELECT last_value, is_called FROM ${seq}`);
  return { last: Number(r!.last_value), called: Boolean(r!.is_called) };
}

describePg('realign id counters + the roster row a failed member save never wrote', () => {
  beforeAll(async () => {
    const parsed = new URL(url);
    if (parsed.hostname !== '127.0.0.1' && parsed.hostname !== 'localhost') throw new Error('refusing a non-local TEST_DATABASE_URL');
    admin = postgres(url, { max: 1 });
    await admin.unsafe(`DROP DATABASE IF EXISTS ${DB} WITH (FORCE)`);
    await admin.unsafe(`CREATE DATABASE ${DB}`);
    a = postgres(urlFor(DB), { max: 1, prepare: false, onnotice: () => {} });
  });

  afterAll(async () => {
    await a?.end();
    if (admin) {
      await admin.unsafe(`DROP DATABASE IF EXISTS ${DB} WITH (FORCE)`);
      await admin.end();
    }
  });

  beforeEach(async () => {
    await a.unsafe(FIXTURE);
  });

  test('the roster insert collides before, and goes through after', async () => {
    const before = a.unsafe(APP_ROSTER_INSERT, ['SR-006', 'New Rep', 'new@example.com', 999]);
    expect(await codeOf(before)).toBe('23505');

    await applyMigration(a);

    const [made] = await a.unsafe(APP_ROSTER_INSERT, ['SR-900', 'New Rep', 'new@example.com', 999]);
    const [{ max }] = await a.unsafe(`SELECT max(id) AS max FROM public.sales_reps WHERE id <> $1`, [made!.id]);
    expect(Number(made!.id)).toBe(Number(max) + 1);
  });

  test('every Sales member who is not disabled and has no roster row gets one, numbered after the highest code', async () => {
    await applyMigration(a);

    const reps = await a<Array<{ code: string; name: string; email: string | null; user_id: string; status: string; archived_at: string | null }>>`
      SELECT code, name, email, user_id, status, archived_at FROM public.sales_reps
       WHERE user_id IN (167, 168, 169, 170) ORDER BY user_id`;
    expect(reps.map((r) => [Number(r.user_id), r.code, r.name, r.status, r.archived_at])).toEqual([
      [167, 'SR-006', 'James Lee Jun Ji', 'active', null],
      // A blank name falls back to the email, as `user.name || user.email` does.
      [168, 'SR-007', 'blank@example.com', 'active', null],
    ]);

    const activity = await a<Array<{ to_value: string; action: string; note: string }>>`
      SELECT a.to_value, a.action, a.note FROM public.sales_team_activity a ORDER BY a.to_value`;
    expect(activity.map((r) => [r.to_value, r.action])).toEqual([['SR-006', 'created'], ['SR-007', 'created']]);
    expect(activity[0]!.note).toContain('Auto-created from Team (department set to Sales)');

    // Kris already has a row; it is not doubled.
    const [{ n }] = await a`SELECT count(*)::int AS n FROM public.sales_reps WHERE user_id = 101`;
    expect(n).toBe(1);
  });

  test('a counter that is behind moves to its table; one already ahead is not moved back', async () => {
    await applyMigration(a);

    expect(await counter('public.project_finance_project_id_seq')).toEqual({ last: 11, called: true });
    expect(await counter('scm.things_id_seq')).toEqual({ last: 500, called: true });
    const [{ id }] = await a`INSERT INTO scm.things DEFAULT VALUES RETURNING id`;
    expect(id).toBe(501);
  });

  test('a second run changes nothing', async () => {
    // Plain copies: a postgres.js result list also carries connection state.
    const snapshot = async () => ({
      reps: JSON.stringify(await a`SELECT id, code, user_id FROM public.sales_reps ORDER BY id`),
      activity: JSON.stringify(await a`SELECT id, rep_id FROM public.sales_team_activity ORDER BY id`),
      counter: await counter('public.sales_reps_id_seq'),
    });
    await applyMigration(a);
    const first = await snapshot();

    await applyMigration(a);

    expect(await snapshot()).toEqual(first);
  });
});
